export type TcIcon = keyof typeof TC_ICONS;

/** An icon's grid as one SVG path: each row's runs of lit pixels as rectangles, in a 16 box */
export function tcIconPath(rows: readonly string[]): string {
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      let e = x;
      while (e < row.length && row[e] === '#') e++;
      d += `M${x} ${y}h${e - x}v1h${x - e}z`;
      x = e;
    }
  });
  return d;
}
